#!/usr/bin/env python3
"""End-to-end plumbing check: grokbot tape -> substrate -> calibration.

Writes to a THROWAWAY substrate (MYCELIUM_DB is pointed at a temp file), never
to the live one.

READ THIS BEFORE QUOTING ANY NUMBER IT PRINTS
---------------------------------------------
The tape below is GENERATED, not recorded. It exists to prove the wiring: that
a grokbot-shaped JSONL file produces traces the substrate accepts, that the
close records arrive with a `score` next to a `pnl`, and that the calibration
joins them. It says nothing whatsoever about pump.fun, about grokbot's score,
or about what any strategy earns.

The honest-limit rule from the convergence work applies unchanged: fixtures
confirm the maths and the plumbing; only a live tape confirms the wiring
against reality. A uniform-looking result from a fixture is evidence of
nothing. Replace `--tape` with a real logs/trades.jsonl before believing a
single number.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

BANNER = """
+----------------------------------------------------------------------+
|  SYNTHETIC TAPE -- PLUMBING CHECK ONLY                                |
|  Generated by this script, not recorded from any market.              |
|  No number printed below is evidence about pump.fun or about the      |
|  entry score's value. It is evidence that the bridge and the          |
|  calibration are wired to each other correctly.                       |
+----------------------------------------------------------------------+
"""


def make_tape(path: Path, n: int = 260, seed: int = 20260929) -> dict:
    """Generate a grokbot-shaped tape using the real record envelopes.

    Field names come from grokbot's src/log.py (_write adds ts + mode;
    buy nests scores; close carries score flat beside pnl_sol). The score is
    generated to be *weakly* informative on purpose -- so the calibration has
    something real to measure rather than a trivially perfect correlation that
    would flatter the harness.
    """
    rng = random.Random(seed)
    counts = {"intent": 0, "buy": 0, "skip": 0, "close": 0}
    with path.open("w", encoding="utf-8") as fh:
        for i in range(n):
            mint = f"SYN{i:04d}"
            score = round(rng.uniform(0.25, 0.97), 4)
            ts = 1_760_000_000 + i * 90
            # weaker than score, so the harness has to actually measure
            win_p = 0.35 * score + 0.20
            bought = rng.random() < 0.45

            if not bought:
                fh.write(json.dumps({
                    "type": "skip", "mint": mint, "symbol": f"S{i}",
                    "stage": rng.choice(["monitor", "analyzer", "scoring", "checker", "risk"]),
                    "reason": rng.choice(["risk_score", "thin_curve", "creator_share", "no_meta"]),
                    "detail": "", "scores": {"total": score, "audit": score, "narrative": score,
                                             "timing": score, "metrics": score},
                    "ts": float(ts), "mode": "dry_run",
                }, ensure_ascii=False) + "\n")
                counts["skip"] += 1
                if rng.random() < 0.72:
                    continue

            fh.write(json.dumps({
                "type": "intent", "mint": mint, "symbol": f"S{i}",
                "size_sol": 0.05, "score": score, "ts": float(ts), "mode": "dry_run",
            }, ensure_ascii=False) + "\n")
            counts["intent"] += 1

            fh.write(json.dumps({
                "type": "buy", "mint": mint, "symbol": f"S{i}", "name": f"Token {i}",
                "size_sol": 0.05, "entry_price": 0.0000123, "tx_hash": "dry_run",
                "scores": {"total": score, "audit": round(score * 0.9, 4),
                           "narrative": round(score * 0.8, 4), "timing": round(score * 0.7, 4),
                           "metrics": round(score * 0.95, 4)},
                "audit": {"confidence": round(score * 0.9, 4), "flags": []},
                "narrative": {"virality": round(score * 0.7, 4)},
                "timing": {"market_sentiment": 0.6},
                "checker": {"approve": True, "confidence": 0.5, "reason": ""},
                "metrics": {"risk_score": round(10 - score * 8, 2), "creator_share": 0.03,
                            "sniper_count": 2, "wallet_diversity": 0.6, "curve_health": 0.7,
                            "unique_wallets": 40, "round_trip_cost_pct": 6.2,
                            "curve_liquidity_sol": 22.5},
                "prompt_versions": {"auditor": "v1"},
                "token": {"age_seconds": 320, "unique_buyers": 9, "curve_progress": 0.22,
                          "market_cap_sol": 31.0, "creator": f"CREATOR{i % 17}"},
                "ts": float(ts), "mode": "dry_run",
            }, ensure_ascii=False) + "\n")
            counts["buy"] += 1

            pnl_pct = rng.uniform(18.0, 240.0) if rng.random() < win_p else rng.uniform(-78.0, -12.0)
            fh.write(json.dumps({
                "type": "close", "mint": mint, "symbol": f"S{i}",
                "creator": f"CREATOR{i % 17}",
                "entry_price": 0.0000123,
                "exit_price": round(0.0000123 * (1 + pnl_pct / 100.0), 12),
                "pnl_sol": round(0.05 * pnl_pct / 100.0, 6),
                "pnl_pct": round(pnl_pct, 2),
                "hold_seconds": rng.uniform(120, 5400),
                "reason": rng.choice(["take_profit", "stop_loss", "trailing", "max_hold", "raydium"]),
                "fraction": 1.0, "final": True, "tx_hash": "dry_run",
                "score": score, "ts": float(ts + 600), "mode": "dry_run",
            }, ensure_ascii=False) + "\n")
            counts["close"] += 1
    return counts


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="grokbot -> Mycelium plumbing check")
    parser.add_argument("--tape", help="use a REAL grokbot logs/trades.jsonl instead of a fixture")
    parser.add_argument("--n", type=int, default=260)
    args = parser.parse_args(argv)

    substrate_path = str(ROOT / ".." / "mycelium-tools" / "packages" / "mycelium-substrate")
    os.environ["MYCELIUM_SUBSTRATE_PATH"] = substrate_path
    sys.path.insert(0, substrate_path)

    workdir = Path(tempfile.mkdtemp(prefix="gmbridge-demo-"))
    db = workdir / "mycelium.db"
    os.environ["MYCELIUM_DB"] = str(db)

    import mycelium_substrate.core as core
    core.init_db(str(db))

    from gmbridge import bridge, calibrate

    if args.tape:
        tape = Path(args.tape)
        print(f"USING REAL TAPE: {tape}")
        print("  (numbers below are measured from a real grokbot log)")
    else:
        tape = workdir / "trades.jsonl"
        counts = make_tape(tape, n=args.n)
        print(BANNER)
        print(f"generated fixture: {counts}")

    cursor = workdir / "cursor.json"

    print("\n-- pass 1: sync")
    first = bridge.sync(tape, store=core, cursor_path=cursor)
    print(json.dumps(first, indent=2))

    print("\n-- pass 2: sync again (must emit nothing)")
    second = bridge.sync(tape, store=core, cursor_path=cursor)
    print(f"emitted={second['emitted']}  read={second['read']}  "
          f"{'IDEMPOTENT' if second['emitted'] == 0 else 'DUPLICATED -- BUG'}")

    rows = core.query_traces(agent="grokbot-pumpfun", limit=100000)
    closes = calibrate.closes_from(rows)
    skips = [r for r in rows if (dict(r).get("action") == "pumpfun.skip")]
    report = calibrate.build_report(closes, unverifiable_skips=len(skips))
    print(calibrate.format_report(report))

    if report["measured"]:
        finding = calibrate.emit_finding(report, store=core)
        print(f"finding persisted: {finding.get('id')}")
        print(f"  confidence (MEASURED): {finding['confidence']}")
        print(f"  {finding['title']}")
    else:
        print("no finding: sample insufficient -- correctly refused to invent one")

    print(f"\nthrowaway substrate: {db}")
    print("(nothing was written to the live ~/mycelium/mycelium.db)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
